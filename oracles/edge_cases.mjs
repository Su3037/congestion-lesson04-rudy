// Produces docs/edge-cases.md by running every implementation on named cases.
// Grid for this table: 4×2 square tiles of 3×3 on a 12×6 chip, so OpenROAD's
// square-tile kernel can run too. Values are per-tile demand totals, x-major.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as R from "../site/js/rudy.js";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const harness = path.join(root, ".cache/upstream/harness");
if (!fs.existsSync(harness)) execFileSync("bash", [path.join(root, "oracles/upstream/run.sh")], { stdio: "inherit" });
const tsrc = fs.readFileSync(path.join(root, "research/teacher/congestion-core.js"), "utf8").replace(/^import .*canvas-hires\.js";\s*$/m, "const fitHiDpiCanvas=()=>{}; const LAB_CANVAS_CSS_HEIGHT=0;");
fs.writeFileSync(path.join(root, ".cache/teacher-core.mjs"), tsrc);
const T = await import(pathToFileURL(path.join(root, ".cache/teacher-core.mjs")).href);

const prob = (nets) => ({ chip: { W: 12, H: 6 }, gcell: { nx: 4, ny: 2, cellW: 3, cellH: 3 }, nets });
const cases = [
  ["Ordinary box", "(1,1)–(8,5)", [["a", "b"]], { a: { x: 1, y: 1 }, b: { x: 8, y: 5 } }],
  ["Corner exactly on a tile edge", "(1,1)–(3,2), x=3 is the edge", [["a", "b"]], { a: { x: 1, y: 1 }, b: { x: 3, y: 2 } }],
  ["Horizontal line net", "(1,1)–(8,1)", [["a", "b"]], { a: { x: 1, y: 1 }, b: { x: 8, y: 1 } }],
  ["Vertical line net", "(2,1)–(2,5)", [["a", "b"]], { a: { x: 2, y: 1 }, b: { x: 2, y: 5 } }],
  ["Line lying on a tile edge", "(1,3)–(8,3), y=3 is the edge", [["a", "b"]], { a: { x: 1, y: 3 }, b: { x: 8, y: 3 } }],
  ["Coincident pins", "(4,4)–(4,4)", [["a", "b"]], { a: { x: 4, y: 4 }, b: { x: 4, y: 4 } }],
  ["Far chip edge", "(10,1)–(12,6)", [["a", "b"]], { a: { x: 10, y: 1 }, b: { x: 12, y: 6 } }],
  ["Four-pin net", "(1,1),(8,1),(1,5),(8,5)", [["a", "b", "c", "d"]], { a: { x: 1, y: 1 }, b: { x: 8, y: 1 }, c: { x: 1, y: 5 }, d: { x: 8, y: 5 } }],
];
const fmt = (arr) => "[" + arr.map((v) => (Math.abs(v) < 1e-12 ? "0" : R.fracText(v, 12))).join(", ") + "]";
const rows = [];
for (const [name, geo, nets, pos] of cases) {
  const p = prob(nets);
  const P = R.computeDemand(p, pos).demand.flat();
  const A = R.computeDemand(p, pos, { model: "A" }).demand.flat();
  // teacher's core hard-codes 3×4 tiles, so run its tile logic through solvers.py with this grid instead
  const py = execFileSync("python3", ["-I", "-c", `
import json,sys; sys.path.insert(0, ${JSON.stringify(path.join(root, "research/teacher"))})
from solvers import rudy_demand
d=rudy_demand(json.loads(sys.argv[1]), {"gcell":{"nx":4,"ny":2,"cellW":3,"cellH":3},"capacity":2,"nets":json.loads(sys.argv[2])})
print(json.dumps([v for col in d for v in col]))`, JSON.stringify(pos), JSON.stringify(nets)], { encoding: "utf8" });
  const teacher = JSON.parse(py);
  const line = [4, 2, 3, 3, nets.length, ...nets.flatMap((n) => [n.length, ...n.flatMap((k) => [pos[k].x, pos[k].y])])].join(" ");
  const [h, v, o] = execFileSync(harness, { input: line + "\n", encoding: "utf8" }).trim().split("\n");
  const dp = h.split(" ").slice(1).map(Number).map((x, i) => x + Number(v.split(" ")[i + 1]));
  const or = o.split(" ").slice(1).map((x) => (Number(x) * 9) / 100); // back from percent of a 3×3 tile to wire length
  rows.push(`| ${name} | ${geo} | ${fmt(teacher)} | ${fmt(P)} | ${fmt(A)} | ${fmt(dp)} | ${fmt(or)} |`);
}
// Teacher behaviour on invalid input (documented in the source audit)
const tBad = [];
try { const d = T.rudyDemand(T.PLACEMENT, [[]]); tBad.push(`empty net → demand ${JSON.stringify(d)}`); } catch (e) { tBad.push(`empty net → throws ${e.message}`); }
{ const d = T.rudyDemand(T.PLACEMENT); const m = T.overflowMetrics(d, 0); tBad.push(`capacity 0 → total overflow ${m.total}, congestion map ${JSON.stringify(T.congestionMap(d, 0)[3])} (column 3)`); }
{ const d = T.rudyDemand({ ...T.PLACEMENT, A: { x: NaN, y: 1 } }); tBad.push(`NaN coordinate → demand column 0 ${JSON.stringify(d[0])}`); }
{ const d = T.rudyDemand({ ...T.PLACEMENT, A: { x: 40, y: 1 } }); tBad.push(`pin at x=40 (outside the 12-wide chip) → silently clamped, column 3 ${JSON.stringify(d[3].map((x) => +x.toFixed(3)))}`); }
const md = `# Edge cases, produced by running each implementation

Generated by \`node oracles/edge_cases.mjs\`. Do not edit by hand.

Grid for this table: 4 × 2 square tiles of 3 × 3 on a 12 × 6 chip (square so that OpenROAD's kernel, which assumes square tiles, can run). Each cell lists the eight tile values in x-major order \`[t(0,0), t(0,1), t(1,0), t(1,1), …]\`, in wire-length units. OpenROAD's output (percent of tile resource, wire width 1) is converted back to wire length by × tile area ÷ 100. DREAMPlace's value is horizontal + vertical with its RISA weight (1.0828 for the four-pin net).

| Case | Pins | Teacher \`solvers.py\` | Model P (this lesson) | Model A (this lesson) | DREAMPlace kernel | OpenROAD kernel |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}

How to read it:

- Teacher and model P agree on every case (model P *is* the teacher's rule).
- On ordinary boxes, model A, DREAMPlace and OpenROAD agree with each other (DREAMPlace adds its RISA factor on the four-pin net), and all three differ from model P, because they weight by overlap area instead of sharing equally.
- A box corner exactly on a tile edge gives the next tile a full equal share in model P and nothing in the area-weighted tools.
- Line nets and coincident pins are where the implementations split three ways: model P shares the HPWL over the endpoint tiles, model A spreads it along the line (this lesson's stated teaching rule), DREAMPlace returns 0 (zero area ÷ ε), and OpenROAD skips zero-area nets entirely.

## Teacher code on invalid input

The lesson's core rejects all of these with a named error instead (see \`tests/core.test.mjs\`).

${tBad.map((s) => "- " + s).join("\n")}
`;
fs.writeFileSync(path.join(root, "docs/edge-cases.md"), md);
console.log(md);
